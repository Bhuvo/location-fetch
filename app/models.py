from datetime import datetime, timezone
from werkzeug.security import generate_password_hash, check_password_hash
from app.extensions import db

def utc_now():
    """Return current UTC datetime."""
    return datetime.now(timezone.utc)

class Admin(db.Model):
    """Administrator credentials for dashboard access."""
    __tablename__ = "admins"

    id = db.Column(db.Integer, primary_key=True)
    username = db.Column(db.String(80), unique=True, nullable=False, index=True)
    password_hash = db.Column(db.String(255), nullable=False)
    created_at = db.Column(db.DateTime, default=utc_now, nullable=False)

    def set_password(self, password: str) -> None:
        """Hash and store the administrator password."""
        self.password_hash = generate_password_hash(password)

    def check_password(self, password: str) -> bool:
        """Verify the password against the stored hash."""
        return check_password_hash(self.password_hash, password)

    def __repr__(self) -> str:
        return f"<Admin {self.username}>"


class TrackingLink(db.Model):
    """Unique tracking links generated by admin."""
    __tablename__ = "tracking_links"

    id = db.Column(db.Integer, primary_key=True)
    name = db.Column(db.String(120), nullable=False)
    token = db.Column(db.String(64), unique=True, nullable=False, index=True)
    is_active = db.Column(db.Boolean, default=True, nullable=False, index=True)
    created_at = db.Column(db.DateTime, default=utc_now, nullable=False)

    # Relationship to visitor records with cascading delete
    visitors = db.relationship(
        "VisitorRecord", 
        backref="tracking_link", 
        lazy=True, 
        cascade="all, delete-orphan"
    )

    @property
    def consented_count(self) -> int:
        """Number of consented visits recorded for this link."""
        return len(self.visitors)

    def to_dict(self) -> dict:
        """Serialize tracking link to JSON-friendly dictionary."""
        return {
            "id": self.id,
            "name": self.name,
            "token": self.token,
            "is_active": self.is_active,
            "consented_count": len(self.visitors),
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }

    def __repr__(self) -> str:
        return f"<TrackingLink {self.name} [{self.token}]>"


class VisitorRecord(db.Model):
    """Consented visitor IP and approximate geolocation record."""
    __tablename__ = "visitor_records"

    id = db.Column(db.Integer, primary_key=True)
    tracking_link_id = db.Column(
        db.Integer, 
        db.ForeignKey("tracking_links.id", ondelete="CASCADE"), 
        nullable=False, 
        index=True
    )
    ip_address = db.Column(db.String(45), nullable=False, index=True)
    country = db.Column(db.String(100), nullable=True, index=True)
    country_code = db.Column(db.String(10), nullable=True, index=True)
    region = db.Column(db.String(100), nullable=True)
    city = db.Column(db.String(100), nullable=True, index=True)
    postal_code = db.Column(db.String(20), nullable=True)
    latitude = db.Column(db.Float, nullable=True)
    longitude = db.Column(db.Float, nullable=True)
    timezone = db.Column(db.String(50), nullable=True)
    isp = db.Column(db.String(150), nullable=True)
    organization = db.Column(db.String(150), nullable=True)
    asn = db.Column(db.String(50), nullable=True)
    browser = db.Column(db.String(100), nullable=True, index=True)
    operating_system = db.Column(db.String(100), nullable=True, index=True)
    accuracy_radius = db.Column(db.Float, nullable=True)
    confidence = db.Column(db.String(20), default="UNKNOWN", nullable=False, index=True)
    is_city_centre = db.Column(db.Boolean, default=False, nullable=False)
    provider = db.Column(db.String(50), nullable=True)
    provider_comparison = db.Column(db.Text, nullable=True)
    consent_timestamp = db.Column(db.DateTime, nullable=False, default=utc_now)
    created_at = db.Column(db.DateTime, default=utc_now, nullable=False, index=True)

    def to_dict(self) -> dict:
        """Serialize visitor record to JSON-friendly dictionary."""
        return {
            "id": self.id,
            "tracking_link_id": self.tracking_link_id,
            "tracking_link_name": self.tracking_link.name if self.tracking_link else "Unknown",
            "tracking_link_token": self.tracking_link.token if self.tracking_link else "",
            "ip_address": self.ip_address,
            "country": self.country or "Not available",
            "country_code": self.country_code or "N/A",
            "region": self.region or "Not available",
            "city": self.city or "Not available",
            "postal_code": self.postal_code or "Not available",
            "latitude": self.latitude,
            "longitude": self.longitude,
            "timezone": self.timezone or "Not available",
            "isp": self.isp or "Not available",
            "organization": self.organization or "Not available",
            "asn": self.asn or "Not available",
            "accuracy_radius": self.accuracy_radius,
            "confidence": self.confidence or "UNKNOWN",
            "is_city_centre": bool(self.is_city_centre),
            "provider": self.provider or "Not available",
            "has_comparison": bool(self.provider_comparison),
            "browser": self.browser or "Unknown",
            "operating_system": self.operating_system or "Unknown",
            "consent_timestamp": self.consent_timestamp.isoformat() if self.consent_timestamp else None,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }

    def __repr__(self) -> str:
        return f"<VisitorRecord #{self.id} IP={self.ip_address} City={self.city}>"


class SystemSetting(db.Model):
    """Configurable system settings such as retention policy."""
    __tablename__ = "system_settings"

    id = db.Column(db.Integer, primary_key=True)
    key = db.Column(db.String(50), unique=True, nullable=False, index=True)
    value = db.Column(db.String(255), nullable=False)
    updated_at = db.Column(db.DateTime, default=utc_now, onupdate=utc_now)

    @classmethod
    def get_setting(cls, key: str, default: str = "") -> str:
        setting = cls.query.filter_by(key=key).first()
        return setting.value if setting else default

    @classmethod
    def set_setting(cls, key: str, value: str) -> None:
        setting = cls.query.filter_by(key=key).first()
        if setting:
            setting.value = str(value)
            setting.updated_at = utc_now()
        else:
            setting = cls(key=key, value=str(value))
            db.session.add(setting)
        db.session.commit()
